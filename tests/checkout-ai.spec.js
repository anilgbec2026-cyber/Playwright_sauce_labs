const { test, expect } = require('../fixtures/pageFixtures');
const { generateJson } = require('../utils/aiHelper');
const data = require('../test-data/users.json');

// WHY skip: this test calls the Claude API, which needs a key. Without a key the rest of the suite still runs.
test.skip(!process.env.ANTHROPIC_API_KEY, 'ANTHROPIC_API_KEY is not set');

test.describe('Checkout with AI generated data', () => {
  test.beforeEach(async ({ loginPage, inventoryPage }) => {
    await loginPage.goto();
    await loginPage.login(data.users.standard.username, data.users.standard.password);
    await expect(inventoryPage.title).toHaveText('Products');
  });

  test('checkout succeeds with customer data generated by Claude', async ({ inventoryPage, cartPage, checkoutPage }) => {
    // Arrange: ask Claude for realistic fake customer data
    const customer = await generateJson(
      'Generate one fictional customer as JSON with exactly these string keys: firstName, lastName, postalCode.'
    );
    await inventoryPage.addToCart(data.products.backpack);
    await inventoryPage.openCart();
    // Act
    await cartPage.checkout();
    await checkoutPage.fillCustomerInfo(customer);
    await checkoutPage.finish();
    // Assert
    await expect(checkoutPage.confirmationHeader).toBeVisible();
  });
});
